-- Pacientes (WhatsApp obrigatório e único)
CREATE TABLE IF NOT EXISTS public.pacientes_crmap (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  telefone text NOT NULL,
  telefone_norm text NOT NULL,
  sessoes_realizadas integer NOT NULL DEFAULT 0 CHECK (sessoes_realizadas >= 0),
  observacoes text,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  UNIQUE (telefone_norm)
);

CREATE OR REPLACE FUNCTION public._normalizar_telefone(p_tel text)
RETURNS text
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
  d text;
BEGIN
  d := regexp_replace(COALESCE(p_tel, ''), '\D', '', 'g');
  IF length(d) >= 10 AND left(d, 2) = '55' THEN
    d := substring(d from 3);
  END IF;
  IF length(d) < 10 OR length(d) > 11 THEN
    RETURN NULL;
  END IF;
  RETURN d;
END;
$$;

ALTER TABLE public.consultas_agendadas
  ADD COLUMN IF NOT EXISTS paciente_id bigint REFERENCES public.pacientes_crmap(id),
  ADD COLUMN IF NOT EXISTS numero_sessao integer,
  ADD COLUMN IF NOT EXISTS tipo_cobranca text NOT NULL DEFAULT 'gratuita'
    CHECK (tipo_cobranca IN ('gratuita', 'paga')),
  ADD COLUMN IF NOT EXISTS valor_consulta numeric(10,2),
  ADD COLUMN IF NOT EXISTS valor_repasse_crmap numeric(10,2),
  ADD COLUMN IF NOT EXISTS repasse_confirmado boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS comunicou_pagamento boolean NOT NULL DEFAULT false;

-- Vincular consultas antigas a pacientes (telefone existente)
DO $$
DECLARE
  r record;
  v_norm text;
  v_pid bigint;
BEGIN
  FOR r IN
    SELECT id, nome_paciente, telefone
    FROM public.consultas_agendadas
    WHERE paciente_id IS NULL AND telefone IS NOT NULL AND trim(telefone) <> ''
  LOOP
    v_norm := public._normalizar_telefone(r.telefone);
    IF v_norm IS NULL THEN
      CONTINUE;
    END IF;
    INSERT INTO public.pacientes_crmap (nome, telefone, telefone_norm)
    VALUES (r.nome_paciente, trim(r.telefone), v_norm)
    ON CONFLICT (telefone_norm) DO UPDATE
      SET nome = EXCLUDED.nome, updated_at = timezone('utc'::text, now())
    RETURNING id INTO v_pid;
    IF v_pid IS NULL THEN
      SELECT id INTO v_pid FROM public.pacientes_crmap WHERE telefone_norm = v_norm;
    END IF;
    UPDATE public.consultas_agendadas SET paciente_id = v_pid WHERE id = r.id;
  END LOOP;
END $$;

CREATE OR REPLACE FUNCTION public._saude_cfg(p_chave text)
RETURNS text
LANGUAGE sql
STABLE
AS $$
  SELECT valor FROM public.saude_config WHERE chave = p_chave LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public._saude_senha_coord_ok(p_senha text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT COALESCE(p_senha, '') IN ('270797crmap*', 'secretaria2026');
$$;

CREATE OR REPLACE FUNCTION public._saude_prof_ok(p_prof_id bigint, p_senha text)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profissionais_saude
    WHERE id = p_prof_id AND ativo AND senha_acesso = p_senha
  );
$$;

CREATE OR REPLACE FUNCTION public._saude_sessoes_gratuitas()
RETURNS integer
LANGUAGE sql
STABLE
AS $$
  SELECT COALESCE(NULLIF(public._saude_cfg('sessoes_gratuitas'), '')::integer, 8);
$$;

CREATE OR REPLACE FUNCTION public.login_profissional_saude(
  p_profissional_id bigint,
  p_senha text
)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_nome text;
BEGIN
  IF NOT public._saude_prof_ok(p_profissional_id, p_senha) THEN
    RETURN json_build_object('success', false, 'message', 'Profissional ou senha incorretos');
  END IF;
  SELECT nome INTO v_nome FROM public.profissionais_saude WHERE id = p_profissional_id;
  RETURN json_build_object(
    'success', true,
    'role', 'profissional',
    'profissional_id', p_profissional_id,
    'nome', v_nome
  );
END;
$$;

