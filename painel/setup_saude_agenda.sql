CREATE TABLE IF NOT EXISTS public.profissionais_saude (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  cargo text,
  ativo boolean NOT NULL DEFAULT true,
  ordem integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.consultas_agendadas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profissional_id bigint NOT NULL REFERENCES public.profissionais_saude(id),
  nome_paciente text NOT NULL,
  telefone text,
  data_consulta date NOT NULL,
  hora_inicio time NOT NULL,
  duracao_min integer NOT NULL DEFAULT 50 CHECK (duracao_min > 0 AND duracao_min <= 240),
  tipo_atendimento text NOT NULL DEFAULT 'Acolhimento',
  observacoes text,
  status text NOT NULL DEFAULT 'agendada'
    CHECK (status IN ('agendada', 'realizada', 'cancelada', 'falta')),
  criado_por text,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now()),
  updated_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS idx_consultas_data ON public.consultas_agendadas (data_consulta, hora_inicio);
CREATE INDEX IF NOT EXISTS idx_consultas_prof ON public.consultas_agendadas (profissional_id, data_consulta);

ALTER TABLE public.profissionais_saude ENABLE ROW LEVEL SECURITY;
